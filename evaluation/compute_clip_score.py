"""
Compute CLIP Score between generated images and their text prompts.

Measures alignment between text prompts and generated images.
Paper uses CLIP Score on MS COCO 30k validation dataset.

Usage:
    python3 -m evaluation.compute_clip_score \
        --image_dir /path/to/generated_images \
        --prompts_file /path/to/prompts.jsonl
"""

import argparse
import json
import os
import torch
from PIL import Image
from tqdm import tqdm


def parse_args():
    parser = argparse.ArgumentParser(description="Compute CLIP Score.")
    parser.add_argument("--image_dir", type=str, required=True, help="Path to generated images")
    parser.add_argument("--prompts_file", type=str, default=None,
                        help="Path to prompts.jsonl (generated by generate_coco.py). "
                             "If not set, looks for prompts.jsonl in image_dir.")
    parser.add_argument("--device", type=str, default="cuda")
    parser.add_argument("--batch_size", type=int, default=32)
    parser.add_argument("--model_name", type=str, default="openai/clip-vit-large-patch14")
    return parser.parse_args()


def main():
    args = parse_args()

    # Find prompts file
    prompts_file = args.prompts_file
    if prompts_file is None:
        prompts_file = os.path.join(args.image_dir, "prompts.jsonl")
    if not os.path.exists(prompts_file):
        print(f"Prompts file not found at {prompts_file}")
        print("See --prompts_file argument.")
        return

    # Load prompts
    prompts = []
    with open(prompts_file, "r") as f:
        for line in f:
            data = json.loads(line)
            prompts.append(data["prompt"])

    # Load CLIP model
    print("Loading CLIP model...")
    try:
        import clip
        model, preprocess = clip.load(args.model_name, device=args.device)
    except ImportError:
        print("openai-clip not found, trying transformers...")
        try:
            from transformers import CLIPModel, CLIPProcessor
            model = CLIPModel.from_pretrained(args.model_name).to(args.device)
            processor = CLIPProcessor.from_pretrained(args.model_name)
            _use_transformers = True
        except ImportError:
            print("Please install clip:")
            print("  pip install git+https://github.com/openai/CLIP.git")
            print("  or")
            print("  pip install transformers")
            return

    # Load images
    image_files = sorted([
        f for f in os.listdir(args.image_dir)
        if f.endswith(('.png', '.jpg', '.jpeg')) and f != "prompts.jsonl"
    ])

    if len(image_files) == 0:
        print(f"No images found in {args.image_dir}")
        return

    print(f"Found {len(image_files)} images, {len(prompts)} prompts")
    n = min(len(image_files), len(prompts))

    scores = []
    for i in tqdm(range(0, n, args.batch_size)):
        batch_files = image_files[i:i + args.batch_size]
        batch_prompts = prompts[i:i + args.batch_size]

        try:
            if 'clip' in dir() and '_use_transformers' not in dir():
                # OpenAI CLIP
                images = torch.stack([
                    preprocess(Image.open(os.path.join(args.image_dir, f)).convert("RGB"))
                    for f in batch_files
                ]).to(args.device)

                text_tokens = clip.tokenize(batch_prompts).to(args.device)

                with torch.no_grad():
                    image_features = model.encode_image(images)
                    text_features = model.encode_text(text_tokens)
                    image_features = image_features / image_features.norm(dim=-1, keepdim=True)
                    text_features = text_features / text_features.norm(dim=-1, keepdim=True)
                    similarity = (image_features @ text_features.T).diag()
                    scores.extend(similarity.cpu().tolist())
            else:
                # Transformers CLIP
                images_pil = [
                    Image.open(os.path.join(args.image_dir, f)).convert("RGB")
                    for f in batch_files
                ]
                inputs = processor(
                    text=batch_prompts,
                    images=images_pil,
                    return_tensors="pt",
                    padding=True
                ).to(args.device)

                with torch.no_grad():
                    outputs = model(**inputs)
                    logits_per_image = outputs.logits_per_image
                    # CLIP score is the diagonal of the similarity matrix
                    similarity = logits_per_image.diag()
                    scores.extend(similarity.cpu().tolist())

        except Exception as e:
            print(f"Error at batch {i}: {e}")
            continue

    if len(scores) > 0:
        avg_score = sum(scores) / len(scores)
        print(f"\n{'='*50}")
        print(f"  CLIP Score: {avg_score:.4f}")
        print(f"  Paper reference (SD1.4 baseline): 30.95")
        print(f"  Paper reference (DUO β=500 nudity): ~30.88")
        print(f"  Paper reference (DUO β=250 nudity): 30.84")
        print(f"  Paper reference (DUO β=1000 violence): 30.78")
        print(f"{'='*50}\n")
    else:
        print("No scores computed.")


if __name__ == "__main__":
    main()
