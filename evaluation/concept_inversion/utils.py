def load_unlearn_pipeline(unlearn_model_path, device, exp_type, dtype=torch.float16):
    """Load original SD1.4 + DUO LoRA (the unlearned model being attacked)."""
    from diffusers import (
        DPMSolverMultistepScheduler,
        StableDiffusionPipeline,
    )

    pipe = StableDiffusionPipeline.from_pretrained(
        "CompVis/stable-diffusion-v1-4", torch_dtype=dtype
    ).to(device)
    pipe.scheduler = DPMSolverMultistepScheduler.from_config(pipe.scheduler.config)
    pipe.safety_checker = None
    pipe.set_progress_bar_config(disable=True)

    if exp_type == "violence":
        cfg_list = ["Blood", "Gun", "Horror", "Suffer"]
        for cfg in cfg_list:
            for cand in (
                f"{unlearn_model_path}/{cfg}/pytorch_lora_weights.safetensors",
                f"{unlearn_model_path}/{cfg}/checkpoint-500/pytorch_lora_weights.safetensors",
                f"{unlearn_model_path}/{cfg}/checkpoint-1000/pytorch_lora_weights.safetensors",
            ):
                if os.path.exists(cand):
                    pipe.load_lora_weights(cand, adapter_name=cfg)
                    break
        pipe.set_adapters(cfg_list, adapter_weights=[1, 1, 1, 1])
    else:
        lora_path = f"{unlearn_model_path}/pytorch_lora_weights.safetensors"
        if not os.path.exists(lora_path):
            for sub in ("checkpoint-500", "checkpoint-1000", "checkpoint-1500"):
                cand = f"{unlearn_model_path}/{sub}/pytorch_lora_weights.safetensors"
                if os.path.exists(cand):
                    lora_path = cand
                    break
        if not os.path.exists(lora_path):
            raise FileNotFoundError(f"LoRA not found in {unlearn_model_path}")
        pipe.load_lora_weights(lora_path)
    pipe.enable_vae_slicing()
    pipe.enable_vae_tiling()
    return pipe


def load_original_pipeline(device, dtype=torch.float16):
    """Original SD1.4 (no LoRA) - generates the anchor NSFW images."""
    from diffusers import (
        DPMSolverMultistepScheduler,
        StableDiffusionPipeline,
    )

    pipe = StableDiffusionPipeline.from_pretrained(
        "CompVis/stable-diffusion-v1-4", torch_dtype=dtype
    ).to(device)
    pipe.scheduler = DPMSolverMultistepScheduler.from_config(pipe.scheduler.config)
    pipe.safety_checker = None  # MUST be disabled for NSFW anchors
    pipe.set_progress_bar_config(disable=True)
    pipe.enable_vae_slicing()
    return pipe


# -----------------------------------------------------------------------------
# Textual inversion of <c> on the unlearned pipeline
# -----------------------------------------------------------------------------
def textual_inversion(
    pipe,
    device,
    anchor_dir,
    prompts_df,
    placeholder_token="<c>",
    initializer_token="man",
    max_steps=3000,
    batch_size=4,
    lr=5e-3,
    num_anchors=None,
):
    """Train a single new token <c> via textual inversion on `pipe`.

    `pipe` already has the DUO LoRA loaded (the model under attack). We learn
    an embedding for <c> so that "<c> <prompt>" reproduces the NSFW anchors.

    Paper Appendix C.2: Adam, lr=5e-3, batch_size=4, 3000 steps.
    CCE reference: caption = "<c> " + anchor's own I2P prompt; every row
    except <c> is restored to its original embedding after each step.
    """
    tokenizer = pipe.tokenizer
    text_encoder = pipe.text_encoder
    vae = pipe.vae
    unet = pipe.unet
    from diffusers import DDPMScheduler

    noise_scheduler = DDPMScheduler.from_config(pipe.scheduler.config)

    # 1. Add <c> token (must be its own single token id)
    num_added = tokenizer.add_tokens(placeholder_token)
    if num_added > 0:
        text_encoder.resize_token_embeddings(len(tokenizer))
    token_id = tokenizer.convert_tokens_to_ids(placeholder_token)
    if token_id in tokenizer.all_special_ids:
        raise ValueError(
            f"Placeholder token {placeholder_token} collided with a special "
            f"token id {token_id}; choose a different placeholder."
        )

    # 2. Initialize <c> with the embedding of an existing word
    init_ids = tokenizer.encode(initializer_token, add_special_tokens=False)
    init_id = init_ids[0]
    embed_layer = text_encoder.get_input_embeddings()
    embed_layer.weight.data[token_id] = embed_layer.weight.data[init_id].clone()

    # 3. Freeze everything; only <c>'s embedding row is trainable
    for p in text_encoder.parameters():
        p.requires_grad = False
    for p in unet.parameters():
        p.requires_grad = False
    for p in vae.parameters():
        p.requires_grad = False
    embed_layer.weight.requires_grad = True

    optimizer = torch.optim.Adam(
        [embed_layer.weight], lr=lr, betas=(0.9, 0.999), weight_decay=0.0
    )

    # 4. Image preprocessing
    import torchvision

    image_transforms = torchvision.transforms.Compose(
        [
            torchvision.transforms.Resize(
                (512, 512),
                interpolation=torchvision.transforms.InterpolationMode.BILINEAR,
            ),
            torchvision.transforms.CenterCrop(512),
            torchvision.transforms.ToTensor(),
            torchvision.transforms.Normalize([0.5], [0.5]),
        ]
    )

    # 5. Load anchor images (filename {i:04d}.png maps to prompts_df.iloc[i])
    image_paths = sorted(
        os.path.join(anchor_dir, f)
        for f in os.listdir(anchor_dir)
        if f.endswith(".png")
    )
    assert image_paths, f"No anchor images found in {anchor_dir}"
    if num_anchors:
        image_paths = image_paths[:num_anchors]

    pil_images = []
    captions = []
    for p in image_paths:
        img = Image.open(p).convert("RGB")
        pil_images.append(image_transforms(img))
        idx = int(os.path.basename(p).split(".")[0])
        captions.append(f"{placeholder_token} {prompts_df.iloc[idx]['prompt']}")
    pixel_values_bank = torch.stack(pil_images).to(device, dtype=torch.float16)

    # fp32 master embedding (lr=5e-3 on fp16 rows overflows to NaN); UNet fp16.
    text_encoder = text_encoder.to(device, dtype=torch.float32)
    unet = unet.to(device, dtype=torch.float16)
    vae = vae.to(device, dtype=torch.float32)

    def build_input_ids(caption_texts):
        input_ids = tokenizer(
            caption_texts,
            padding="max_length",
            truncation=True,
            max_length=tokenizer.model_max_length,
            return_tensors="pt",
        )
        return input_ids.input_ids.to(device)

    print(
        f"[textual_inversion] max_steps={max_steps} bs={batch_size} lr={lr} "
        f"anchors={pixel_values_bank.shape[0]} token_id={token_id}"
    )

    orig_embeds_params = embed_layer.weight.data.clone()
    losses = []
    rng = np.random.default_rng(42)
    if hasattr(torch, "amp") and hasattr(torch.amp, "GradScaler"):
        scaler = torch.amp.GradScaler("cuda")
        @torch.amp.autocast("cuda", dtype=torch.float16)
        def unet_forward(noisy_latents, timesteps, embeds):
            return unet(noisy_latents, timesteps, embeds).sample
    else:
        scaler = torch.cuda.amp.GradScaler()
        @torch.cuda.amp.autocast(dtype=torch.float16)
        def unet_forward(noisy_latents, timesteps, embeds):
            return unet(noisy_latents, timesteps, embeds).sample

    for step in range(max_steps):
        idxs = rng.choice(
            pixel_values_bank.shape[0],
            size=min(batch_size, pixel_values_bank.shape[0]),
            replace=True,
        )
        batch_pixels = pixel_values_bank[idxs]

        with torch.no_grad():
            latents = (
                vae.encode(batch_pixels.to(torch.float32)).latent_dist.sample()
                * vae.config.scaling_factor
            )
            noise = torch.randn_like(latents)
            timesteps = torch.randint(
                0,
                noise_scheduler.config.num_train_timesteps,
                (latents.shape[0],),
                device=device,
            ).long()
            noisy_latents = noise_scheduler.add_noise(latents, noise, timesteps)

        input_ids = build_input_ids([captions[i] for i in idxs])
        embeds = embed_layer(input_ids)
        noisy_latents = noisy_latents.to(unet.dtype)
        embeds = embeds.to(unet.dtype)
        noise_pred = unet_forward(noisy_latents, timesteps, embeds)
        loss = F.mse_loss(noise_pred.float(), noise.float(), reduction="mean")

        if not torch.isfinite(loss):
            print(
                f"[textual_inversion] WARNING: NaN loss at step {step+1} "
                f"(noise_pred range = [{noise_pred.min():.3f}, {noise_pred.max():.3f}])"
            )

        scaler.scale(loss).backward()
        torch.nn.utils.clip_grad_norm_([embed_layer.weight], max_norm=1.0)
        scaler.step(optimizer)
        scaler.update()
        optimizer.zero_grad()

        # Restore every row except <c> (CCE reference safeguard).
        with torch.no_grad():
            index_no_updates = torch.ones(
                (len(tokenizer),), dtype=torch.bool, device=device
            )
            index_no_updates[token_id] = False
            embed_layer.weight.data[index_no_updates] = orig_embeds_params[
                index_no_updates
            ]

        losses.append(loss.item())
        if (step + 1) % 200 == 0:
            print(
                f"[textual_inversion] step={step+1}/{max_steps} "
                f"loss={float(np.mean(losses[-200:])):.4f}"
            )

    torch.cuda.empty_cache()
    gc.collect()
    return embed_layer.weight.data[token_id].detach().cpu()


