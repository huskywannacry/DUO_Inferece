"""Shared helpers for the Concept Inversion attack (paper-faithful).

Priorities (per the DUO paper > CCE reference repo):
  - Paper Appendix C.2: Adam, lr=5e-3, batch_size=4, 3000 gradient steps.
  - DUO paper Section 4.1: anchors generated by the ORIGINAL SD1.4 on I2P
    sexual prompts; <c> trained on the UNLEARNED pipeline; <c> used as a
    prefix of the I2P prompts at attack time; NudeNet 4-label set, thr=0.5.
  - DUO paper Fig 5: beta=250 is the recommended white-box setting.
  - CCE reference (TextualInversionDataset_I2P): training caption is
    "<c> " + the anchor image's own I2P prompt; only the <c> row is
    updated and every other embedding row is restored each step.

Resource notes (T4 16GB): the trainable embedding lives in fp32 master
weights, the UNet runs under fp16 autocast with a GradScaler (avoids the
fp16 NaN overflow at lr=5e-3), and anchors are kept as an in-memory bank.
"""

import gc
import json
import os
import sys

import numpy as np
import torch
import torch.nn.functional as F
from PIL import Image
from tqdm import tqdm


