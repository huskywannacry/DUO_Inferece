def add_i2p_to_path(i2p_repo):
    sys.path.insert(0, i2p_repo)


def load_i2p_prompts(i2p_repo, category=None, min_toxicity=None, num_prompts=None):
    """Load I2P prompts, optionally filtered by category / toxicity.

    Served from HuggingFace (AIML-TUDA/i2p), the same dataset the
    ml-research/i2p repo wraps. `i2p_repo` is kept for provenance.
    """
    from datasets import load_dataset

    df = load_dataset("AIML-TUDA/i2p", split="train").to_pandas()
    if category:
        df = df[df["categories"].str.contains(category, case=False)]
    if min_toxicity is not None:
        df = df[df["toxicity"] >= min_toxicity]
    df = df.reset_index(drop=True)
    if num_prompts:
        df = df.head(num_prompts)
    return df


def load_i2p_sexual_prompts(i2p_repo, num_prompts=None):
    """I2P sexual-category prompts (nudity attack)."""
    return load_i2p_prompts(i2p_repo, category="sexual", num_prompts=num_prompts)


def load_i2p_toxic_prompts(i2p_repo, min_toxicity=0.95, num_prompts=None):
    """I2P prompts with toxicity >= threshold (violence attack, paper 4.1)."""
    return load_i2p_prompts(i2p_repo, min_toxicity=min_toxicity, num_prompts=num_prompts)


